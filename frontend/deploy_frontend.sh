# deploy_fronted.sh
#!/bin/bash

# ==============================================================================
# 配置變數（請根據你的環境確認名稱）
# ==============================================================================
S3_BUCKET="2026-cloud-native-frontend"
CLOUDFRONT_DIST_ID="EQZ875I9UF2ZJ"

echo "===================================================="
echo "🚀 開始執行 Vue 前端自動化打包與 S3/CloudFront 部署"
echo "===================================================="


# ------------------------------------------------------------------------------
# 2. 晶片/環境防呆：確認 node_modules 狀態
# ------------------------------------------------------------------------------
if [ ! -d "node_modules" ]; then
    echo "📦 偵測到尚未安裝相依套件，正在執行 npm install..."
    npm install
else
    echo "ℹ️  node_modules 已存在，準備開始打包..."
fi

# 💡 如果你未來又遇到晶片錯誤（例如 Rollup 找不到模組），請把下面三行取消註解以啟用強制重置：
# echo "🔄 強制重置相依套件以避免晶片架構錯誤..."
# rm -rf node_modules package-lock.json && npm cache clean --force && npm install

# ------------------------------------------------------------------------------
# 3. 執行 Vite 生產環境編譯 (Build)
# ------------------------------------------------------------------------------
echo "🛠️  正在執行 npm run build 打包成 dist 靜態檔案..."
npm run build

if [ $? -ne 0 ]; then
    echo "❌ 錯誤：Vue 專案編譯失敗！請檢查前端程式碼語法。"
    exit 1
fi

if [ ! -d "dist" ]; then
    echo "❌ 錯誤：編譯完成但找不到 dist 資料夾！"
    exit 1
fi

echo "✅ 前端打包成功！已產生純靜態 HTML/JS/CSS。"

# ------------------------------------------------------------------------------
# 4. 上傳並同步至 S3（攤平在根目錄，不包含 dist 資料夾本身）
# ------------------------------------------------------------------------------
echo "📤 正在同步 dist/ 內容至 S3 Bucket: s3://${S3_BUCKET} ..."

# 💡 --delete 參數非常關鍵：它會清除 S3 上舊版本有、但新版本已經刪除的廢棄快取檔案
aws s3 sync dist/ s3://${S3_BUCKET} --delete

if [ $? -ne 0 ]; then
    echo "❌ 錯誤：同步到 S3 失敗，請檢查 AWS 憑證或 Bucket 權限！"
    exit 1
fi

echo "✅ S3 靜態資源同步成功！"

# ------------------------------------------------------------------------------
# 5. 自動刷新 CloudFront 快取 (Invalidation)
# ------------------------------------------------------------------------------
echo "⏳ 正在通知 AWS CloudFront 清除舊快取 (全站刷新 /*) ..."

aws cloudfront create-invalidation \
    --distribution-id ${CLOUDFRONT_DIST_ID} \
    --paths "/*" > /dev/null

if [ $? -eq 0 ]; then
    echo "✨ CloudFront 快取刷新指令已成功送出！"
else
    echo "⚠️  警告：CloudFront 快取刷新失敗，使用者可能需要手動重整或等待快取過期。"
fi

echo "===================================================="
echo "🎉 前端部署完全成功！"
echo "🌐 你的前端網站：https://angrysquirrel.qzz.io"
echo "===================================================="